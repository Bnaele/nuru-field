-- Nuru Field — migrate a database built by the original hackathon app
--
-- The hackathon build shipped a different schema from the one in schema.sql, and
-- `create table if not exists` cannot repair it: where a table already exists the
-- statement is a no-op, so the old columns survive and every new write fails.
--
-- What was actually found in the paused project when it was resumed (read from the
-- PostgREST schema):
--
--   crop_reference   old shape — name, category, min_temp, max_temp, min_rainfall,
--                    max_rainfall, optimal_soil_ph, growing_season, province.
--                    No scientific_name, family, min_ph, max_ph or source, so the
--                    crop endpoint cannot insert a catalogue row.
--   plants           old shape — field_id, crop_name, date_planted, status, notes,
--                    all NOT NULL where the API now writes name / crop_type /
--                    planting_date. Every insert fails. Holds 0 rows.
--   field_profiles   half-migrated — has both old and new columns, and the old
--                    `field_name` is still NOT NULL, so saving a profile whose
--                    label is "back bed" fails on a column nothing reads.
--   soil_scans       matches schema.sql. Untouched.
--   plant_photos     matches, plus a nullable `caption`. Untouched.
--   market_prices    missing.
--   plant_waterings  missing.
--
-- Run order in the Supabase SQL editor:
--   1. this file
--   2. schema.sql           (creates the two missing tables and their policies)
--   3. python backend/seed.py
--
-- This file is deliberately narrow: it drops only tables whose contents are either
-- empty or regenerable from the FAO ECOCROP archive, and it relaxes the one stale
-- constraint instead of deleting anyone's rows.

-- Regenerated by backend/seed.py from backend/data/crop_reference.csv, so the 42
-- hand-written rows from the hackathon build are replaced rather than migrated.
drop table if exists crop_reference cascade;

-- Empty, and its column names share nothing with the current API.
drop table if exists plants cascade;

-- Both are new in schema.sql; dropping first makes this file safe to re-run.
drop table if exists plant_waterings cascade;
drop table if exists market_prices cascade;

-- `field_name` predates `label` and is not written by the API, but it is NOT NULL,
-- so it rejects every insert that omits it. The column stays (50 rows of team demo
-- data reference it); only the constraint goes.
do $$
begin
    if exists (
        select 1 from information_schema.columns
        where table_schema = 'public'
          and table_name = 'field_profiles'
          and column_name = 'field_name'
          and is_nullable = 'NO'
    ) then
        alter table field_profiles alter column field_name drop not null;
    end if;
end $$;

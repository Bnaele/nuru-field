"""Match a field's measured conditions against real crop envelopes.

Where the numbers come from
---------------------------
`data/crop_reference.csv` is generated by `data/build_crop_data.py` from the FAO
ECOCROP dataset archived at Zenodo (DOI 10.5281/zenodo.13319716). Each crop's
optimal temperature, rainfall and pH windows are measurements from that dataset,
not hand-written guesses. Regenerate with:

    python data/build_crop_data.py

Coverage is every taxon the archive can score: 2,066 species covering fruit,
vegetables, herbs, spices, nuts, grains, legumes, oilseeds, fodder, fibre, timber,
medicinal and ornamental plants. ECOCROP only carries scientific names, so a crop
with no curated common name keeps its Latin name rather than being dropped, and
carries its botanical family instead.

Finding a plant
---------------
A grower who already has a plant in mind does not want a shortlist, so `query`
searches the whole catalogue by common name, scientific name, botanical family or
South African vernacular name (VERNACULAR_ALIASES), and skips the score floor.
The score and the cautions still come back, so "mango" in a cold field returns
the mango and says why it would struggle instead of returning nothing. Local
names matter here: ECOCROP has never heard of amadumbe, morogo or naartjie, and a
search that answers those with an empty list looks broken.

What the scorer does
--------------------
The old matcher asked "which province is this?" and returned every crop tagged
with that province, so a recommendation had no relationship to the field. This one
compares the field's *own* measurements against each crop's envelope:

* temperature 0.40 - this month's 10-year mean
* rainfall    0.35 - mean annual total over 10 years
* soil pH     0.25 - SoilGrids 0-30 cm mean

Season enters through the temperature signal: this month's measured mean *is* the
seasonal signal, so there is no invented planting-calendar table to go stale.
Weights renormalise over whichever inputs are present, and both rainfall and pH
are genuinely absent for a few species, so the scorer never assumes a value it
was not given.

Within a window a crop scores 0.85-1.0 depending on how centrally the field sits,
and the factor decays across one window-width outside it. A flat 1.0 for anything
inside made six crops tie at 100 and the ranking carried no information.

Soil texture is treated separately on purpose. ECOCROP has no texture envelope, so
scoring against one would be fabrication. Texture instead makes a small, capped
adjustment for crops with a well-known sensitivity (roots forking in heavy clay),
and every such crop gets a `cautions` line saying the guidance is general agronomy
rather than a measured threshold.

Confidence drops when an input is missing, so a field whose soil lookup failed can
never display "high confidence".
"""

from __future__ import annotations

import asyncio
import csv
from datetime import date
from functools import lru_cache
from pathlib import Path

from config import current_season
from sources.http import UpstreamError
from sources.weather import get_field_climate
from sources.soilgrids import get_soil_profile

REFERENCE_CSV = Path(__file__).with_name("data") / "crop_reference.csv"
ECOCROP_ATTRIBUTION = "Crop envelopes: FAO ECOCROP (via Zenodo 10.5281/zenodo.13319716)"

WEIGHT_TEMP = 0.40
WEIGHT_RAIN = 0.35
WEIGHT_PH = 0.25

# Texture adjustment is deliberately small: it should break ties between
# climatically-equivalent crops, never promote a crop whose climate is wrong.
TEXTURE_MAX_SHIFT = 0.08

# Crops whose marketable part is a root, tuber or bulb, so heavy soil matters.
ROOT_CROPS = {
    "Carrot", "Potato", "Sweet potato", "Beetroot", "Onion", "Radish", "Turnip",
    "Cassava", "Yam", "Garlic", "Parsnip", "Ginger", "Turmeric", "Leek", "Shallot",
}

HEAVY_TEXTURES = {
    "clay", "silty clay", "sandy clay", "clay loam", "silty clay loam", "silt", "silt loam",
}
LIGHT_TEXTURES = {"sand", "loamy sand", "sandy loam"}

UNCATEGORISED = "Other"

# South African vernacular names.
#
# ECOCROP carries scientific names, and the curated list adds the English name a
# seed packet would use. Neither includes what a grower here actually types, so
# "amadumbe" or "spanspek" returned nothing even though the plant was in the
# catalogue all along. An alias maps a local word onto the species it names; it is
# a search key only and never renames a row.
VERNACULAR_ALIASES: dict[str, tuple[str, ...]] = {
    "amadumbe": ("Colocasia esculenta",),
    "madumbe": ("Colocasia esculenta",),
    "naartjie": ("Citrus reticulata",),
    "nartjie": ("Citrus reticulata",),
    "spanspek": ("Cucumis melo",),
    "mielie": ("Zea mays",),
    "mealie": ("Zea mays",),
    "morogo": (
        "Amaranthus cruentus", "Amaranthus dubius", "Amaranthus hypochondriacus",
        "Amaranthus lividus", "Amaranthus hybridus", "Amaranthus tricolor",
        "Chenopodium album", "Solanum nigrum",
    ),
    "imifino": (
        "Amaranthus cruentus", "Amaranthus dubius", "Amaranthus hypochondriacus",
        "Amaranthus lividus", "Amaranthus hybridus", "Amaranthus tricolor",
        "Chenopodium album", "Solanum nigrum",
    ),
    "gem squash": ("Cucurbita pepo",),
    "patty pan": ("Cucurbita pepo",),
    "pawpaw": ("Carica papaya",),
    "kikuyu": ("Pennisetum clandestinum",),
    "napier": ("Pennisetum purpureum",),
    "num-num": ("Carissa macrocarpa", "Carissa edulis"),
    "num num": ("Carissa macrocarpa", "Carissa edulis"),
    "waterberry": ("Syzygium cordatum",),
    "kei apple": ("Dovyalis caffra",),
    "umdoni": ("Syzygium cordatum",),
}


@lru_cache(maxsize=1)
def _alias_index() -> dict[str, frozenset[str]]:
    """Alias word -> the species it names, lowercased once."""
    return {word: frozenset(species) for word, species in VERNACULAR_ALIASES.items()}


# Ordering bonus for crops with a known common name. Displayed scores are never
# adjusted; this only decides who appears first when two crops score alike, so a
# grower sees "Cabbage" before an unnamed forestry species with the same fit.
NAMED_ORDER_BONUS = 5


def _optional_float(value: str | None) -> float | None:
    if value is None:
        return None
    text = value.strip()
    if not text:
        return None
    try:
        number = float(text)
    except ValueError:
        return None
    return None if number != number else number


def _range(row: dict, low_key: str, high_key: str) -> tuple[float, float] | None:
    low = _optional_float(row.get(low_key))
    high = _optional_float(row.get(high_key))
    if low is None or high is None:
        return None
    return (low, high) if high >= low else (high, low)


@lru_cache(maxsize=1)
def load_reference() -> tuple[dict, ...]:
    """Read the generated ECOCROP extract once per process."""
    if not REFERENCE_CSV.exists():
        raise UpstreamError(
            "Crop reference data is missing. Run `python data/build_crop_data.py` "
            "in the backend directory to regenerate it.",
            status_code=500,
        )

    crops: list[dict] = []
    with REFERENCE_CSV.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            temperature = _range(row, "min_temp", "max_temp")
            if temperature is None:
                # Without a temperature window the crop cannot be scored at all.
                continue
            name = (row.get("name") or "").strip()
            scientific = (row.get("scientific_name") or "").strip()
            if not name or not scientific:
                continue
            crops.append(
                {
                    "name": name,
                    "scientific_name": scientific,
                    "family": (row.get("family") or "").strip(),
                    "category": (row.get("category") or UNCATEGORISED).strip(),
                    "temperature": temperature,
                    "rainfall": _range(row, "min_rainfall_mm", "max_rainfall_mm"),
                    "ph": _range(row, "min_ph", "max_ph"),
                    "has_common_name": name != scientific,
                    "source": row.get("source") or ECOCROP_ATTRIBUTION,
                }
            )
    return tuple(crops)


def _fit(value: float, low: float, high: float) -> tuple[float, float, float]:
    """How well `value` sits in [low, high]: (factor 0-1, signed gap, centring).

    Inside scores 0.85-1.0 by how central the value is, decaying across one
    window-width outside, so a crop is not recommended on a technicality when the
    field is barely outside its range.
    """
    span = max(high - low, 1.0)
    if low <= value <= high:
        midpoint = (low + high) / 2
        centring = 1.0 - 2 * abs(value - midpoint) / span  # 1 centre, 0 edge
        return 0.85 + 0.15 * centring, 0.0, round(centring, 2)

    gap = low - value if value < low else value - high
    return max(0.0, 0.85 * (1.0 - gap / span)), round(gap, 1), 0.0


def _texture_adjustment(crop: dict, texture: str | None) -> tuple[float, str | None]:
    """Small, capped nudge plus an optional caution string."""
    if not texture:
        return 0.0, None

    is_root = crop["name"] in ROOT_CROPS
    if texture in HEAVY_TEXTURES:
        if is_root:
            return -TEXTURE_MAX_SHIFT, (
                f"{texture} soil is heavy - roots and bulbs can fork or rot. "
                "Plant on ridges or in raised beds."
            )
        return -TEXTURE_MAX_SHIFT * 0.5, (
            f"{texture} soil drains slowly. General agronomy guidance, not an "
            "ECOCROP threshold."
        )
    if texture in LIGHT_TEXTURES:
        if is_root:
            return TEXTURE_MAX_SHIFT * 0.5, (
                f"{texture} soil suits roots and bulbs, but dries out fast."
            )
        rainfall = crop.get("rainfall")
        if rainfall and rainfall[1] >= 900:
            return -TEXTURE_MAX_SHIFT * 0.5, (
                f"{texture} soil holds little water, and this crop wants up to "
                f"{rainfall[1]:g} mm a year. Plan to irrigate."
            )
        return 0.0, None
    return 0.0, None


def _confidence(score: int, inputs_used: int) -> str:
    if inputs_used >= 3 and score >= 75:
        return "high"
    if inputs_used >= 2 and score >= 55:
        return "medium"
    return "low"


def _format_range(window: tuple[float, float] | None, unit: str = "") -> str | None:
    if not window:
        return None
    suffix = f" {unit}" if unit else ""
    return f"{window[0]:g}-{window[1]:g}{suffix}"


def evaluate_crop(crop: dict, context: dict) -> dict:
    """Score one crop against a field context. Pure, so it is unit-testable."""
    month_name = context.get("month_name") or "this month"
    texture = context.get("texture_class")

    signals = (
        ("Temperature", context.get("same_month_mean_temp_c"), crop["temperature"], WEIGHT_TEMP, "°C"),
        ("Rainfall", context.get("annual_rainfall_mm"), crop["rainfall"], WEIGHT_RAIN, "mm/year"),
        ("Soil pH", context.get("ph"), crop["ph"], WEIGHT_PH, ""),
    )

    weighted = 0.0
    weight_total = 0.0
    inputs_used = 0
    centrings: list[float] = []
    temperature_gap: float | None = None
    temperature_fit = 0.0
    reasons: list[str] = []
    cautions: list[str] = []

    for label, value, window, weight, unit in signals:
        if value is None or window is None:
            continue
        low, high = window
        fit, gap, centring = _fit(value, low, high)
        inputs_used += 1
        weighted += fit * weight
        weight_total += weight
        centrings.append(centring)

        if label == "Temperature":
            temperature_gap, temperature_fit = gap, fit

        unit_text = f" {unit}" if unit else ""
        shown = f"{value:g}{unit_text}"
        expect = f"{low:g}-{high:g}{unit_text}"
        if gap == 0.0:
            reasons.append(f"{label}: {shown} is inside its {expect} window")
        else:
            direction = "below" if value < low else "above"
            cautions.append(
                f"{label}: {shown} is {abs(gap):g}{unit_text} {direction} its "
                f"{expect} window - this crop would need help to make it"
            )

    base = weighted / weight_total if weight_total else 0.0
    shift, texture_note = _texture_adjustment(crop, texture)
    if texture_note:
        (cautions if shift < 0 else reasons).append(texture_note)

    score = round(max(0.0, min(1.0, base + shift)) * 100)

    if context.get("same_month_mean_temp_c") is None:
        cautions.append("This month's temperature is unavailable, so the fit is a guess.")
    if context.get("ph") is None:
        cautions.append("Soil pH is unavailable here, so soil fit was not checked.")
    if crop["rainfall"] is None:
        cautions.append("ECOCROP has no rainfall window for this species.")

    if temperature_gap == 0.0 and temperature_fit > 0:
        growing_season = f"{month_name} suits planting"
    elif temperature_fit >= 0.5:
        growing_season = f"{month_name} is marginal"
    else:
        growing_season = "Outside its planting window now"

    return {
        "name": crop["name"],
        "scientific_name": crop["scientific_name"],
        "family": crop["family"],
        "category": crop["category"],
        "has_common_name": crop["has_common_name"],
        "score": score,
        "confidence": _confidence(score, inputs_used),
        "centring": round(min(centrings), 2) if centrings else 0.0,
        "growing_season": growing_season,
        # Kept so existing components keep rendering without a rewrite.
        "optimal_soil_ph": _format_range(crop["ph"]),
        "optimal": {
            "temperature_c": list(crop["temperature"]),
            "rainfall_mm_per_year": list(crop["rainfall"]) if crop["rainfall"] else None,
            "ph": list(crop["ph"]) if crop["ph"] else None,
        },
        "fit": {"temperature": _format_range(crop["temperature"], "°C"),
                "rainfall": _format_range(crop["rainfall"], "mm/yr"),
                "ph": _format_range(crop["ph"])},
        "reasons": reasons,
        "cautions": cautions,
        "source": crop["source"],
    }


def rank_crops(
    context: dict,
    *,
    limit: int = 8,
    minimum_score: int = 40,
    categories: set[str] | None = None,
    named_only: bool = True,
    query: str | None = None,
) -> tuple[list[dict], int]:
    """Best-fitting crops for a context, strongest first.

    Returns (crops, number_of_candidates_considered).

    `named_only` keeps the default list actionable: 1,558 of the 2,066 species
    have no curated common name and are listed under their scientific name, which
    is fine for a browse-everything view and useless as a shortlist. Pass False to
    search the whole catalogue.

    `query` is a name search rather than a recommendation. The grower already has
    a plant in mind, so it searches every species by common name, scientific name
    or family, and it does not hide the result behind the minimum score: a mango
    in a cold field is still the plant they asked about, and the score plus the
    cautions say why it would struggle.
    """
    needle = (query or "").strip().lower()
    if needle:
        named_only = False
        minimum_score = 0
    aliased = _alias_index().get(needle, frozenset())

    considered = 0
    scored: list[dict] = []
    for crop in load_reference():
        if categories and crop["category"] not in categories:
            continue
        if named_only and not crop["has_common_name"]:
            continue
        if needle and not (
            needle in crop["name"].lower()
            or needle in crop["scientific_name"].lower()
            or needle in crop["family"].lower()
            or crop["scientific_name"] in aliased
        ):
            continue
        considered += 1
        result = evaluate_crop(crop, context)
        if result["score"] >= minimum_score:
            scored.append(result)

    # The known-name bonus only applies to the shortlist view. When browsing the
    # whole catalogue or searching, the ordering is pure score, so nothing is
    # silently promoted.
    bonus = NAMED_ORDER_BONUS if named_only else 0
    scored.sort(
        key=lambda crop: (
            -(crop["score"] + (bonus if crop["has_common_name"] else 0)),
            -crop["centring"],
            crop["name"],
        )
    )
    return scored[:limit], considered


def _context_from(climate: dict, soil: dict, month_name: str, season: str) -> dict:
    return {
        "month_name": month_name,
        "season": season,
        "same_month_mean_temp_c": climate.get("same_month_mean_temp_c"),
        "annual_rainfall_mm": climate.get("annual_rainfall_mm"),
        "ph": soil.get("ph") if soil.get("available") else None,
        "texture_class": soil.get("texture_class") if soil.get("available") else None,
    }


@lru_cache(maxsize=1)
def category_counts() -> dict[str, int]:
    """How many species sit in each category, for the filter chips.

    Counted from the same reference the scorer uses, so the chips can never
    promise a category that returns nothing.
    """
    counts: dict[str, int] = {}
    for crop in load_reference():
        counts[crop["category"]] = counts.get(crop["category"], 0) + 1
    return dict(sorted(counts.items(), key=lambda pair: (-pair[1], pair[0])))


async def recommend_for(
    latitude: float,
    longitude: float,
    *,
    limit: int = 8,
    categories: set[str] | None = None,
    named_only: bool = True,
    query: str | None = None,
) -> dict:
    """Crops for a coordinate, using its own weather and soil.

    Climate and soil are fetched concurrently and share their caches with the
    field profile endpoint, so this does not add upstream traffic.
    """
    (weather, weather_cached), (soil, soil_cached) = await asyncio.gather(
        get_field_climate(latitude, longitude),
        get_soil_profile(latitude, longitude),
    )

    # Taken from the climate block rather than recomputed: the label must name the
    # month the normals actually cover.
    month_name = weather["climate"].get("same_month_name") or date.today().strftime("%B")
    context = _context_from(weather["climate"], soil, month_name, current_season())

    crops, considered = rank_crops(
        context,
        limit=limit,
        categories=categories,
        named_only=named_only,
        query=query,
    )
    catalogue_size = len(load_reference())
    missing = [
        label
        for label, value in (
            ("temperature", context["same_month_mean_temp_c"]),
            ("rainfall", context["annual_rainfall_mm"]),
            ("soil pH", context["ph"]),
        )
        if value is None
    ]

    return {
        "crops": crops,
        "context": {
            "month": month_name,
            "season": context["season"],
            "mean_temperature_c": context["same_month_mean_temp_c"],
            "annual_rainfall_mm": context["annual_rainfall_mm"],
            "soil_ph": context["ph"],
            "soil_texture": context["texture_class"],
            "missing_inputs": missing,
        },
        "catalogue": {
            "species_scored": considered,
            "species_available": catalogue_size,
            "named_only": named_only,
            "search": query,
            "categories": category_counts(),
        },
        "source": {
            "name": "FAO ECOCROP",
            "attribution": ECOCROP_ATTRIBUTION,
            "method": (
                "Each crop's optimal temperature, rainfall and pH windows are compared "
                "with this field's measured values. Score 0-100; confidence falls when "
                "an input is missing."
            ),
            "cached": weather_cached and soil_cached,
        },
    }

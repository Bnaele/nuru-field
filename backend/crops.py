"""Match a field's measured conditions against real crop envelopes.

Where the numbers come from
---------------------------
`data/crop_reference.csv` is generated by `data/build_crop_data.py` from the FAO
ECOCROP dataset archived at Zenodo (DOI 10.5281/zenodo.13319716). Each crop's
optimal temperature, rainfall and pH windows are measured measurements from that
dataset, not hand-written guesses. Regenerate with:

    python -m data.build_crop_data

Then what we do with them
-------------------------
The old matcher asked "which province is this?" and returned every crop tagged
with that province — a hand-written table with no relationship to the actual
field. This one compares the field's *own* measurements against each crop's
envelope and reports how well each one fits, with the reasons spelled out.

Three signals come from ECOCROP and are weighted:

* temperature 0.40 — this month's 10-year mean
* rainfall    0.35 — mean annual total over 10 years
* soil pH     0.25 — SoilGrids 0-30 cm mean

Season enters through the temperature signal: this month's measured mean *is*
the seasonal signal, so there is no invented planting-calendar table to rot.

Soil texture is treated differently on purpose. ECOCROP carries no texture
envelope, so scoring it against one would be fabrication. Texture instead makes
a small, capped adjustment only for crops with a well-known sensitivity (roots
forking in heavy clay, for example), and every such crop gets a `cautions` line
saying the guidance is general agronomy rather than a measured threshold.

Confidence is reported honestly: it drops when an input is missing, so a field
whose soil lookup failed never shows "high confidence".
"""

from __future__ import annotations

import asyncio
import csv
from datetime import date
from functools import lru_cache
from pathlib import Path

from config import current_season
from sources.http import UpstreamError
from sources.open_meteo import get_field_climate
from sources.soilgrids import get_soil_profile

REFERENCE_CSV = Path(__file__).with_name("data") / "crop_reference.csv"
ECOCROP_ATTRIBUTION = "Crop envelopes: FAO ECOCROP (via Zenodo 10.5281/zenodo.13319716)"

WEIGHT_TEMP = 0.40
WEIGHT_RAIN = 0.35
WEIGHT_PH = 0.25

# Texture adjustment is deliberately small: it should break ties between
# climatically-equivalent crops, never promote a crop whose climate is wrong.
TEXTURE_MAX_SHIFT = 0.08

# Crops whose marketable part is a root, tuber or bulb, so heavy soil matters.
ROOT_CROPS = {
    "Carrot", "Potato", "Sweet potato", "Beetroot", "Onion", "Radish", "Turnip",
    "Cassava", "Yam", "Garlic", "Parsnip", "Ginger", "Turmeric",
}

HEAVY_TEXTURES = {
    "clay", "silty clay", "sandy clay", "clay loam", "silty clay loam", "silt", "silt loam",
}
LIGHT_TEXTURES = {"sand", "loamy sand", "sandy loam"}


@lru_cache(maxsize=1)
def load_reference() -> tuple[dict, ...]:
    """Read the generated ECOCROP extract once per process."""
    if not REFERENCE_CSV.exists():
        raise UpstreamError(
            "Crop reference data is missing. Run `python -m data.build_crop_data` "
            "in the backend directory to regenerate it.",
            status_code=500,
        )

    crops: list[dict] = []
    with REFERENCE_CSV.open(encoding="utf-8", newline="") as handle:
        for row in csv.DictReader(handle):
            try:
                crops.append(
                    {
                        "name": row["name"],
                        "scientific_name": row["scientific_name"],
                        "category": row["category"],
                        "min_temp": float(row["min_temp"]),
                        "max_temp": float(row["max_temp"]),
                        "min_rainfall_mm": float(row["min_rainfall_mm"]),
                        "max_rainfall_mm": float(row["max_rainfall_mm"]),
                        "min_ph": float(row["min_ph"]),
                        "max_ph": float(row["max_ph"]),
                        "source": row.get("source") or ECOCROP_ATTRIBUTION,
                    }
                )
            except (KeyError, TypeError, ValueError):
                # A malformed row should cost one crop, not the whole list.
                continue
    return tuple(crops)


def _fit(value: float | None, low: float, high: float) -> tuple[float, float | None, float]:
    """How well `value` sits in [low, high]: (factor 0-1, signed gap, centring).

    Inside the window scores between 0.85 and 1.0 rather than a flat 1.0: a field
    in the middle of a crop's optimal range has more room to absorb a bad season
    than one sitting on the boundary. Without that, every crop whose window
    happens to contain the field ties at 100 and the ranking carries no
    information.

    Outside the window the factor decays linearly across one window-width, so a
    crop is not recommended on a technicality when the field is barely outside.
    """
    if value is None:
        return 0.0, None, 0.0

    span = max(high - low, 1.0)
    if low <= value <= high:
        midpoint = (low + high) / 2
        centring = 1.0 - 2 * abs(value - midpoint) / span  # 1 centre, 0 edge
        return 0.85 + 0.15 * centring, 0.0, round(centring, 2)

    gap = low - value if value < low else value - high
    return max(0.0, 0.85 * (1.0 - gap / span)), round(gap, 1), 0.0


def _texture_adjustment(crop: dict, texture: str | None) -> tuple[float, str | None]:
    """Small, capped nudge plus an optional caution string."""
    if not texture:
        return 0.0, None

    is_root = crop["name"] in ROOT_CROPS
    if texture in HEAVY_TEXTURES:
        if is_root:
            return -TEXTURE_MAX_SHIFT, (
                f"{texture} soil is heavy — roots and bulbs can fork or rot. "
                "Plant on ridges or in raised beds."
            )
        return -TEXTURE_MAX_SHIFT * 0.5, (
            f"{texture} soil drains slowly. General agronomy guidance, not an "
            "ECOCROP threshold."
        )
    if texture in LIGHT_TEXTURES:
        if is_root:
            return TEXTURE_MAX_SHIFT * 0.5, (
                f"{texture} soil suits roots and bulbs, but dries out fast."
            )
        if crop["max_rainfall_mm"] >= 900:
            return -TEXTURE_MAX_SHIFT * 0.5, (
                f"{texture} soil holds little water, and this crop wants "
                f"up to {crop['max_rainfall_mm']:.0f} mm a year. Plan to irrigate."
            )
        return 0.0, None
    return 0.0, None


def _confidence(score: float, inputs_used: int) -> str:
    if inputs_used >= 3 and score >= 75:
        return "high"
    if inputs_used >= 2 and score >= 55:
        return "medium"
    return "low"


def evaluate_crop(crop: dict, context: dict) -> dict:
    """Score one crop against a field context. Pure, so it is unit-testable."""
    temp = context.get("same_month_mean_temp_c")
    rain = context.get("annual_rainfall_mm")
    ph = context.get("ph")
    texture = context.get("texture_class")
    month_name = context.get("month_name") or "this month"

    temp_fit, temp_gap, temp_centring = _fit(temp, crop["min_temp"], crop["max_temp"])
    rain_fit, rain_gap, rain_centring = _fit(rain, crop["min_rainfall_mm"], crop["max_rainfall_mm"])
    ph_fit, ph_gap, ph_centring = _fit(ph, crop["min_ph"], crop["max_ph"])

    weighted = 0.0
    weight_total = 0.0
    inputs_used = 0
    centrings: list[float] = []
    reasons: list[str] = []
    cautions: list[str] = []

    for value, fit, gap, centring, weight, label, unit, span in (
        (temp, temp_fit, temp_gap, temp_centring, WEIGHT_TEMP, "Temperature", "°C", (crop["min_temp"], crop["max_temp"])),
        (rain, rain_fit, rain_gap, rain_centring, WEIGHT_RAIN, "Rainfall", "mm/year", (crop["min_rainfall_mm"], crop["max_rainfall_mm"])),
        (ph, ph_fit, ph_gap, ph_centring, WEIGHT_PH, "Soil pH", "", (crop["min_ph"], crop["max_ph"])),
    ):
        if value is None:
            continue
        inputs_used += 1
        weighted += fit * weight
        weight_total += weight
        centrings.append(centring)

        low, high = span
        window = f"{low:g}–{high:g}{(' ' + unit) if unit else ''}"
        if gap == 0.0:
            reasons.append(f"{label}: {value:g}{(' ' + unit) if unit else ''} is inside its {window} window")
        elif gap is not None and gap > 0:
            short = "below" if value < low else "above"
            gap_text = f"{abs(gap):g}{(' ' + unit) if unit else ''}"
            cautions.append(
                f"{label}: {value:g}{(' ' + unit) if unit else ''} is {gap_text} {short} "
                f"its {window} window — this crop would need help to make it"
            )

    base = weighted / weight_total if weight_total else 0.0
    shift, texture_note = _texture_adjustment(crop, texture)
    if texture_note:
        (cautions if shift < 0 else reasons).append(texture_note)

    score = round(max(0.0, min(1.0, base + shift)) * 100)

    if temp is None:
        cautions.append("This month's temperature is unavailable, so the fit is a guess.")
    if ph is None:
        cautions.append("Soil pH is unavailable here, so soil fit was not checked.")

    if temp_gap == 0.0 and context.get("same_month_mean_temp_c") is not None:
        growing_season = f"{month_name} suits planting"
    elif temp_fit >= 0.5:
        growing_season = f"{month_name} is marginal"
    else:
        growing_season = "Outside its planting window now"

    return {
        "name": crop["name"],
        "scientific_name": crop["scientific_name"],
        "category": crop["category"],
        "score": score,
        "confidence": _confidence(score, inputs_used),
        "centring": round(min(centrings), 2) if centrings else 0.0,
        "growing_season": growing_season,
        # Kept so existing components keep rendering without a rewrite.
        "optimal_soil_ph": f"{crop['min_ph']:g}–{crop['max_ph']:g}",
        "optimal": {
            "temperature_c": [crop["min_temp"], crop["max_temp"]],
            "rainfall_mm_per_year": [crop["min_rainfall_mm"], crop["max_rainfall_mm"]],
            "ph": [crop["min_ph"], crop["max_ph"]],
        },
        "reasons": reasons,
        "cautions": cautions,
        "source": crop.get("source") or ECOCROP_ATTRIBUTION,
    }


def rank_crops(context: dict, *, limit: int = 8, minimum_score: int = 40) -> list[dict]:
    """Best-fitting crops for a context, strongest first.

    Ties break on `centring` — how comfortably the field sits inside each window —
    so a crop centred in its range outranks one grazing the boundary.
    """
    scored = [evaluate_crop(crop, context) for crop in load_reference()]
    viable = [crop for crop in scored if crop["score"] >= minimum_score]
    viable.sort(key=lambda crop: (-crop["score"], -crop["centring"], crop["name"]))
    return viable[:limit]


def _context_from(climate: dict, soil: dict, today_month_name: str, season: str) -> dict:
    return {
        "month_name": today_month_name,
        "season": season,
        "same_month_mean_temp_c": climate.get("same_month_mean_temp_c"),
        "annual_rainfall_mm": climate.get("annual_rainfall_mm"),
        "ph": soil.get("ph") if soil.get("available") else None,
        "texture_class": soil.get("texture_class") if soil.get("available") else None,
    }


async def recommend_for(latitude: float, longitude: float, *, limit: int = 8) -> dict:
    """Crops for a coordinate, using its own weather and soil.

    Climate and soil are fetched concurrently and share the caches with the field
    profile endpoint, so adding this endpoint did not add upstream traffic.
    """
    climate_task = get_field_climate(latitude, longitude)
    soil_task = get_soil_profile(latitude, longitude)
    (weather, weather_cached), (soil, soil_cached) = await asyncio.gather(climate_task, soil_task)

    month_name = date.today().strftime("%B")
    context = _context_from(weather["climate"], soil, month_name, current_season())

    crops = rank_crops(context, limit=limit)
    missing = [
        label
        for label, value in (
            ("temperature", context["same_month_mean_temp_c"]),
            ("rainfall", context["annual_rainfall_mm"]),
            ("soil pH", context["ph"]),
        )
        if value is None
    ]

    return {
        "crops": crops,
        "context": {
            "month": month_name,
            "season": context["season"],
            "mean_temperature_c": context["same_month_mean_temp_c"],
            "annual_rainfall_mm": context["annual_rainfall_mm"],
            "soil_ph": context["ph"],
            "soil_texture": context["texture_class"],
            "missing_inputs": missing,
        },
        "source": {
            "name": "FAO ECOCROP",
            "attribution": ECOCROP_ATTRIBUTION,
            "method": (
                "Each crop's optimal temperature, rainfall and pH windows are compared "
                "with this field's measured values. Score 0-100; confidence falls when "
                "an input is missing."
            ),
            "cached": weather_cached and soil_cached,
        },
    }
